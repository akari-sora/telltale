#!/usr/bin/env python3
"""Run the existing Mode08 oracle and host regressions against an owned TCP peer.

The JSON guard and child exit must both succeed. No Android/device result or
historical evidence file is generated by this host-only runner.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
from pathlib import Path
import re
import signal
import subprocess
import sys
import time

IDENTITY = "Mode 08 replay reference listening on 127.0.0.1:"
READY = re.compile(r"^Mode 08 replay reference listening on 127\.0\.0\.1:(\d+) \(hash: [0-9a-f]+\)$")


def ready_port(text: str) -> int | None:
    for line in text.splitlines():
        match = READY.fullmatch(line.strip())
        if match:
            port = int(match.group(1))
            if 1 <= port <= 65535:
                return port
    return None


def stop_owned(process: subprocess.Popen | None) -> bool:
    if process is None:
        return True
    if process.poll() is None:
        process.terminate()
        try:
            process.wait(timeout=5)
        except subprocess.TimeoutExpired:
            process.kill()
            process.wait(timeout=5)
    return process.poll() is not None


def checked_run(command: list[str], cwd: Path, stdout: Path, stderr: Path,
                timeout: float) -> int:
    with stdout.open('wb') as out, stderr.open('wb') as err:
        process = subprocess.Popen(command, cwd=cwd, stdout=out, stderr=err,
                                   start_new_session=True)
        try:
            return process.wait(timeout=timeout)
        finally:
            if process.poll() is None:
                # Only this command's own process group; never pkill a port/name.
                os.killpg(process.pid, signal.SIGTERM)
                try:
                    process.wait(timeout=5)
                except subprocess.TimeoutExpired:
                    os.killpg(process.pid, signal.SIGKILL)
                    process.wait(timeout=5)


def run(repo: Path, output: Path, flutter: str, timeout: int) -> int:
    repo = repo.resolve()
    output = output.resolve()
    output.mkdir(parents=True, exist_ok=False)
    fixture = repo / 'tool/obd_test_rig/mode08_replay_fixtures.json'
    result: dict = {
        'schema_version': 1, 'evidence_level': 'host_tcp_integration',
        'android_executed': False, 'ok': False, 'required_visible_cases': 9,
        'fixture_sha256': hashlib.sha256(fixture.read_bytes()).hexdigest(),
        'started_utc': time.strftime('%Y-%m-%dT%H:%M:%SZ', time.gmtime()),
    }
    server = None
    rc = 1
    try:
        for key, argument in [('commit', 'HEAD'), ('tree', 'HEAD^{tree}')]:
            result[key] = subprocess.check_output(
                ['git', 'rev-parse', argument], cwd=repo, text=True).strip()
        server_command = [
            sys.executable, '-u', 'tool/obd_test_rig/mode08_replay_reference.py',
            '--bind', '127.0.0.1', '--port', '0',
            '--log', str(output / 'server_events.jsonl'),
        ]
        result['server_command'] = server_command
        with (output / 'server_stdout.log').open('wb') as out, \
                (output / 'server_stderr.log').open('wb') as err:
            server = subprocess.Popen(server_command, cwd=repo, stdout=out, stderr=err)
        deadline = time.monotonic() + 15
        port = None
        while time.monotonic() < deadline:
            if server.poll() is not None:
                raise RuntimeError(f'Reference server exited: {server.returncode}')
            port = ready_port((output / 'server_stdout.log').read_text(errors='replace'))
            if port is not None:
                break
            time.sleep(0.05)
        if port is None:
            raise TimeoutError('Reference server did not announce a loopback port')
        result['port'] = port
        command = [
            flutter, 'test',
            'test/diagnostics/service_recipes/mode08_replay_oracle_test.dart',
            'test/diagnostics/service_recipes/mode08_d05_supplement_test.dart',
            '--dart-define=MODE08_ORACLE_REQUIRED=true',
            f'--dart-define=MODE08_ORACLE_PORT={port}', '--reporter', 'json',
        ]
        result['test_command'] = command
        runner_exit = checked_run(command, repo, output / 'report.jsonl',
                                  output / 'test_stderr.log', timeout)
        result['runner_exit'] = runner_exit
        guard_command = [
            sys.executable, 'tool/oracle_guard/assert_no_skips.py',
            str(output / 'report.jsonl'), '9', '--runner-exit', str(runner_exit),
            '--evidence-dir', str(output / 'guard'),
        ]
        guard_exit = checked_run(guard_command, repo, output / 'guard_stdout.log',
                                 output / 'guard_stderr.log', 30)
        result['guard_exit'] = guard_exit
        rc = 0 if runner_exit == 0 and guard_exit == 0 else 1
    except (OSError, ValueError, RuntimeError, TimeoutError,
            subprocess.SubprocessError, InterruptedError, KeyboardInterrupt) as exc:
        result['error'] = f'{type(exc).__name__}: {exc}'
        rc = 1
    finally:
        try:
            result['owned_server_stopped'] = stop_owned(server)
        except (OSError, subprocess.SubprocessError) as exc:
            result['cleanup_error'] = str(exc)
            result['owned_server_stopped'] = False
            rc = 1
        result['ok'] = rc == 0 and result['owned_server_stopped']
        result['finished_utc'] = time.strftime('%Y-%m-%dT%H:%M:%SZ', time.gmtime())
        (output / 'result.json').write_text(json.dumps(result, indent=2) + '\n')
    return rc


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--repo', type=Path, default=Path.cwd())
    parser.add_argument('--output-dir', type=Path, required=True)
    parser.add_argument('--flutter', default='flutter')
    parser.add_argument('--timeout', type=int, default=900)
    args = parser.parse_args()
    if not 1 <= args.timeout <= 3600:
        parser.error('--timeout must be 1..3600 seconds')

    def interrupted(_signum, _frame):
        raise InterruptedError('Required-mode run interrupted')
    signal.signal(signal.SIGTERM, interrupted)
    try:
        return run(args.repo, args.output_dir, args.flutter, args.timeout)
    except (OSError, ValueError) as exc:
        print(f'Refusing required-mode run: {exc}', file=sys.stderr)
        return 1


if __name__ == '__main__':
    raise SystemExit(main())
